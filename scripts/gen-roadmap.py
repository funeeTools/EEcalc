"""Generate src/app/roadmap.ts from scripts/roadmap-slugs.json (the planned calculators, as category/slug).

Usage: python3 scripts/gen-roadmap.py scripts/roadmap-slugs.json   (writes src/app/roadmap.ts)
"""
import json, re, sys
slugs = json.load(open(sys.argv[1]))
CATS = [
 ('rf','RF & Microwave','RF','≋'),('pcb','PCB Design','PCB','▦'),('power','Power Electronics','Power','⚡'),
 ('signal','Signal Processing','Signal','∿'),('antenna','Antenna Design','Antenna','⟟'),('general','General Electronics','General','Ω'),
 ('protocol','Communications','Comms','⇄'),('thermal','Thermal','Thermal','♨'),('motor','Motor Control','Motor','⚙'),
 ('emc','EMC / EMI','EMC','⌁'),('sensor','Sensor Interface','Sensor','◉'),('unit-conversion','Unit Conversions','Units','⇋'),
 ('audio','Audio Electronics','Audio','♪'),('iot','IoT & LPWAN','IoT','⌔'),
]
WORDS = {
 'rf':'RF','vswr':'VSWR','db':'dB','dbm':'dBm','ism':'ISM','pcb':'PCB','led':'LED','ldo':'LDO','lc':'LC','rc':'RC','rcd':'RCD',
 'opamp':'Op-Amp','op-amp':'Op-Amp','uart':'UART','i2c':'I²C','i2s':'I²S','dc':'DC','emi':'EMI','eirp':'EIRP','emc':'EMC','esd':'ESD','tvs':'TVS',
 'snr':'SNR','adc':'ADC','fft':'FFT','am':'AM','fm':'FM','spi':'SPI','can':'CAN','usb':'USB','rs485':'RS-485','pwm':'PWM','mosfet':'MOSFET',
 'bjt':'BJT','bldc':'BLDC','pid':'PID','ntc':'NTC','rtd':'RTD','pt100':'PT100','lvdt':'LVDT','awg':'AWG','pll':'PLL','ber':'BER',
 '5g':'5G','nr':'NR','lora':'LoRa','ble':'BLE','lin':'LIN','lm317':'LM317','555':'555','vfd':'VFD','rt60':'RT60','bga':'BGA',
 'q':'Q','h-bridge':'H-Bridge','4-20ma':'4–20 mA','imd':'IMD','pa':'PA','fresnel':'Fresnel','smith':'Smith','wilkinson':'Wilkinson',
 'yagi':'Yagi','doppler':'Doppler','steinmetz':'Steinmetz','wheatstone':'Wheatstone','hall':'Hall','schmitt':'Schmitt','zener':'Zener',
 'nyquist':'Nyquist','johnson':'Johnson','class-d':'Class-D','ppm':'ppm','vs':'vs','to':'to','and':'and','of':'of','per':'per',
 'modbus':'Modbus','delta-wye':'Delta–Wye','gauge':'Gauge','dual':'Dual',
}
TITLE_OVERRIDE = {
 'rf/noise-figure-cascade':'Cascaded Noise Figure','rf/vswr-return-loss':'VSWR / Return Loss','rf/db-converter':'dB Converter',
 'rf/wavelength-frequency':'Wavelength / Frequency','rf/rf-link-budget':'RF Link Budget','rf/return-loss-error':'Return Loss Measurement Error',
 'rf/intermodulation-distortion':'Intermodulation Distortion (IP3)','rf/smith-chart':'Smith Chart & Matching','rf/q-factor':'Q Factor',
 'general/opamp-gain':'Op-Amp Gain','general/opamp-bandwidth':'Op-Amp Bandwidth','general/lm317-resistors':'LM317 Resistors',
 'general/555-timer':'555 Timer','sensor/4-20ma-transmitter':'4–20 mA Transmitter','unit-conversion/dbm-watts':'dBm ↔ Watts',
 'unit-conversion/rectangular-polar':'Rectangular ↔ Polar','unit-conversion/frequency-wavelength':'Frequency ↔ Wavelength',
 'pcb/via-calculator':'Via Calculator','signal/sampling-nyquist':'Sampling / Nyquist','power/ldo-thermal':'LDO Thermal',
 'motor/h-bridge-selection':'H-Bridge Selection','audio/class-d-efficiency':'Class-D Efficiency','general/delta-wye-conversion':'Delta–Wye Conversion',
 'iot/lora-link-budget':'LoRa Link Budget','iot/ble-link-budget':'BLE Link Budget','rf/5g-nr-band-lookup':'5G NR Band Lookup','rf/5g-nr-link-budget':'5G NR Link Budget',
 'signal/filter-designer':'Filter Designer (LC Ladder)',
}
def title(slug):
  if slug in TITLE_OVERRIDE: return TITLE_OVERRIDE[slug]
  name = slug.split('/')[1]
  out=[]
  for w in name.split('-'):
    out.append(WORDS.get(w, w.capitalize()))
  return ' '.join(out)
by = {c[0]:[] for c in CATS}
for s in slugs:
  by[s.split('/')[0]].append(s)
lines = ['/**','* The roadmap: every calculator EEcalc plans to offer, grouped by category (built or not).','* Generated by scripts/gen-roadmap.py from scripts/roadmap-slugs.json — edit titles there, or override in registry.ts.','*/','',
 'export interface RoadmapCategory { id: string; title: string; short: string; icon: string; calcs: { slug: string; title: string }[] }','',
 'export const ROADMAP: RoadmapCategory[] = [']
for cid,t,sh,ic in CATS:
  lines.append(f'  {{ id: {json.dumps(cid)}, title: {json.dumps(t,ensure_ascii=False)}, short: {json.dumps(sh)}, icon: {json.dumps(ic,ensure_ascii=False)}, calcs: [')
  for s in by[cid]:
    lines.append(f'    {{ slug: {json.dumps(s.split("/")[1])}, title: {json.dumps(title(s),ensure_ascii=False)} }},')
  lines.append('  ] },')
lines.append('];')
open('src/app/roadmap.ts','w').write('\n'.join(lines)+'\n')
print({k:len(v) for k,v in by.items()}, sum(len(v) for v in by.values()))
